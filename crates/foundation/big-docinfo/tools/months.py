#!/usr/bin/env python3
"""Writes src/months.rs: month names of BigLinux's alphabetic languages, from glibc.

  python3 tools/months.py > src/months.rs

Source: the glibc locale definitions in /usr/share/i18n/locales (LC_TIME mon,
alt_mon, abmon, ab_alt_mon), which carry both the case a date uses ("4 października")
and the nominative ("październik"). Names are folded exactly as src/text.rs folds
text. A name that means different months in different languages ("listopad" is
October in Croatian and November in Polish) is left out: no date beats a wrong one.
Chinese, Japanese and Korean write months with digits and are matched by pattern.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

LOCALES = Path("/usr/share/i18n/locales")
# BigLinux's interface languages with an alphabetic script.
LANGUAGES = ["be_BY", "bg_BG", "cs_CZ", "da_DK", "de_DE", "el_GR", "en_US", "en_GB", "es_ES", "et_EE",
             "fi_FI", "fr_FR", "he_IL", "hr_HR", "hu_HU", "is_IS", "it_IT", "nb_NO", "nn_NO", "nl_NL",
             "pl_PL", "pt_BR", "pt_PT", "ro_RO", "ru_RU", "sk_SK", "sv_SE", "tr_TR", "uk_UA"]
KEYS = ("mon", "alt_mon", "abmon", "ab_alt_mon")
FOLD = {c: base for chars, base in (("áàâãäå", "a"), ("éèêë", "e"), ("íìîï", "i"), ("óòôõö", "o"),
                                    ("úùûü", "u"), ("ç", "c"), ("ñ", "n"), ("ýÿ", "y"), ("ºᵒ", "o"),
                                    ("ª", "a"), ("¹", "1"), ("²", "2"), ("³", "3")) for c in chars}


def fold(s):
    return "".join(FOLD.get(c, c) for c in s.lower())


def lc_time(locale):
    text = (LOCALES / locale).read_text(encoding="utf-8", errors="replace")
    text = re.sub(r"<U([0-9A-Fa-f]{4,6})>", lambda m: chr(int(m[1], 16)), text)
    section = re.search(r"^LC_TIME\s*$(.*?)^END LC_TIME", text, re.M | re.S)
    if not section:
        return {}
    body = section[1]
    copy = re.search(r'^\s*copy\s+"([^"]+)"', body, re.M)
    names = lc_time(copy[1]) if copy else {}
    joined = re.sub(r"/\s*\n", "", body)  # continuation lines
    for line in joined.splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2 and parts[0] in KEYS:
            names[parts[0]] = re.findall(r'"([^"]*)"', parts[1])
    return names


def main():
    meaning = defaultdict(set)
    for locale in LANGUAGES:
        for key, values in lc_time(locale).items():
            if len(values) != 12:
                continue
            for month, name in enumerate(values, 1):
                name = fold(name.strip().rstrip("."))
                if len(name) >= 3 and name.isalpha():
                    meaning[name].add(month)
                    # Finnish dates take the partitive ("4. lokakuuta"), which glibc lacks.
                    if locale == "fi_FI" and key == "mon":
                        meaning[name + "ta"].add(month)
    table = sorted((name, months.pop()) for name, months in meaning.items() if len(months) == 1)
    dropped = sorted(name for name, months in meaning.items() if len(months) > 1)
    out = sys.stdout
    out.write("// SPDX-FileCopyrightText: 2026 BigLinux contributors\n// SPDX-License-Identifier: MIT\n\n")
    out.write("//! Month names, folded as `text::fold_lower` folds. Generated by `tools/months.py`\n")
    out.write("//! from the glibc locale definitions; do not edit by hand.\n")
    out.write(f"//! Left out as ambiguous between languages: {', '.join(dropped) or 'none'}.\n\n")
    out.write("/// Sorted by name, for binary search.\npub const MONTHS: &[(&str, u32)] = &[\n")
    for name, month in table:
        out.write(f'    ("{name}", {month}),\n')
    out.write("];\n")


if __name__ == "__main__":
    main()
